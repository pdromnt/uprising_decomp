#include "input_controller.h"

static int clear_offsets(GameMemory *memory, GameAddress object,
        const uint16_t *offsets, unsigned count) {
    unsigned index;
    for (index = 0u; index < count; ++index) {
        game_memory_write_u32(memory, object + offsets[index], 0u);
        if (memory->fault) return 0;
    }
    return 1;
}

int game_input_controller_clear_initial(GameMemory *memory,
        GameAddress object) {
    static const uint16_t offsets[] = {
        0x50,0x54,0x58,0x74,0x5c,0x78,0x7c,0x80,0x84,0x60,
        0x90,0x170,0x174,0x08,0x104,0x108,0x10c,0x110,0x114,
        0x0c,0x18,0x4c,0x70,0x88,0x8c,0x9c,0x94,0x98,
        0x78,0x7c,0x80,0x84,0x70,0x74,0x90,0x64,0x68,0x6c,
        0x9c,0xa0,0xa4,0xa8,0xac,0xb0,0xb4,0xb8,0xbc,0xc0,
        0xc4,0xc8,0xcc,0xd0,0xd4,0xd8,0xdc,0xe8,0xec,0xf0,
        0x118,0x11c,0x120,0xe4,0xe0
    };
    if (!memory) return 0;
    return clear_offsets(memory, object, offsets,
        sizeof(offsets) / sizeof(offsets[0]));
}

