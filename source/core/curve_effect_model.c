static const unsigned fields[5]={0x40,0x44,0x4c,0x50,0x54};
static const size_t sizes[5]={0x144,0x1b0,0x240,0x90,0x480};
static float real(GameMemory *m,GameAddress p){uint32_t bits=game_memory_read_u32(m,p);float v;memcpy(&v,&bits,4);return v;}
static void store(GameMemory *m,GameAddress p,float v){uint32_t bits;memcpy(&bits,&v,4);game_memory_write_u32(m,p,bits);}
int curve_effect_model_release(GameMemory *m,GameAddress model,int deleting,const GamePresentationStorageServices *s){
    unsigned i;
    if(!m || !s || !s->release)return 0;
    for(i=0;i<5;i++){unsigned field=fields[i];GameAddress p=game_memory_read_u32(m,model+field);
        if(m->fault || (p && !s->release(s->context,p)))return 0;
        game_memory_write_u32(m,model+field,0);
    }
    game_memory_write_u32(m,model,0x571fa0);return !m->fault && (!deleting || s->release(s->context,model));
}
static int allocate_model(GameMemory *m,GameAddress model,GameAddress material,const GamePresentationStorageServices *s){
    static const unsigned faces[6][3]={{0,1,3},{4,3,1},{1,2,4},{5,4,2},{2,0,5},{3,5,0}};
    GameAddress arrays[5]={0};unsigned i,band,face,corner;
    if(!m || m->fault || !s || !s->allocate || !s->release)return 0;
    game_memory_write_u32(m,model,0x5752d0);
    for(i=0;i<12;i++)store(m,model+4+i*4,(i==0 || i==5 || i==10)?1:0);
    game_memory_write_u32(m,model+0x34,0);game_memory_write_u32(m,model+0x38,0);game_memory_write_u8(m,model+0x3c,0);
    for(i=0;i<5;i++)game_memory_write_u32(m,model+fields[i],0);
    for(i=0;i<5;i++){
        arrays[i]=s->allocate(s->context,sizes[i]);game_memory_write_u32(m,model+fields[i],arrays[i]);
        if(!arrays[i] || m->fault)goto failed;
    }
    for(band=0;band<8;band++)for(face=0;face<6;face++){
        unsigned triangle=band*6+face;GameAddress packet=model+0x58+triangle*40,pointers=arrays[2]+triangle*12;
        game_memory_write_u32(m,packet,3);game_memory_write_u32(m,packet+4,pointers);game_memory_write_u32(m,packet+8,0x1d);
        game_memory_write_u32(m,packet+16,arrays[4]+triangle*24);game_memory_write_u32(m,packet+20,material);
        for(corner=0;corner<3;corner++)game_memory_write_u32(m,pointers+corner*4,arrays[1]+(band*3+faces[face][corner])*16);
    }
    if(!m->fault)return 1;
failed:
    for(i=0;i<5;i++)if(arrays[i]){(void)s->release(s->context,arrays[i]);game_memory_write_u32(m,model+fields[i],0);}
    return 0;
}
/*50bd40: texture dimensions define the same two UV triangles, repeated for
 *the three sides. Positions are generated by the live curve consumer. */
int curve_effect_model_construct(GameMemory *m,GameAddress model,GameAddress material,const GamePresentationStorageServices *s){
    if(!m || m->fault || !model || !s)return 0;
    uint16_t width_word=game_memory_read_u16(m,material),height_word=game_memory_read_u16(m,material+2);int16_t width,height;
    GameAddress uv;float w,h;unsigned triangle;
    memcpy(&width,&width_word,2);memcpy(&height,&height_word,2);
    if(m->fault || !allocate_model(m,model,material,s))return 0;
    uv=game_memory_read_u32(m,model+0x50);w=(float)((long double)width-real(m,0x575288));h=(float)((long double)height-real(m,0x575288));
    for(triangle=0;triangle<6;triangle++){
        const float even[6]={0,0,0,h,w,0},odd[6]={w,h,w,0,0,h};const float *values=(triangle&1)?odd:even;unsigned i;
        for(i=0;i<6;i++)store(m,uv+triangle*24+i*4,values[i]);
    }
    return !m->fault;
}
/*50c190/50c4b0: copy positions and source UVs, rebuild all private pointers. */
GameAddress curve_effect_model_clone(GameMemory *m,GameAddress source,const GamePresentationStorageServices *s){
    GameAddress model;unsigned i,field;
    if(!m || m->fault || !s || !s->allocate || !s->release || game_memory_read_u32(m,source)!=0x5752d0)return 0;
    model=s->allocate(s->context,0x7d8);if(!model)return 0;
    if(!allocate_model(m,model,game_memory_read_u32(m,source+0x6c),s)){(void)s->release(s->context,model);return 0;}
    for(field=0;field<2;field++){
        unsigned offset=field?0x50:0x40,size=field?0x90:0x144;GameAddress input=game_memory_read_u32(m,source+offset),output=game_memory_read_u32(m,model+offset);
        for(i=0;i<size;i+=4)game_memory_write_u32(m,output+i,game_memory_read_u32(m,input+i));
    }
    if(!m->fault)return model;
    (void)curve_effect_model_release(m,model,1,s);return 0;
}
/*50c530: the existing native Bernstein table drives nine rings. Keep the CRT
 *stream distinct from gameplay RNG and preserve the original partial stores. */
int curve_effect_model_present(GameMemory *m,GameAddress model,const float controls[4][3],const float offsets[3][3]){
    if(!m || m->fault || !model || !controls || !offsets)return 0;
    GameAddress positions=game_memory_read_u32(m,model+0x40),source_uv=game_memory_read_u32(m,model+0x50),render_uv=game_memory_read_u32(m,model+0x54);
    unsigned ring,axis,point,band,face;GameplayMeshSubmission submission={0};uint32_t far_bits;int32_t far;
    if(m->fault || game_memory_read_u32(m,model)!=0x5752d0)return 0;
    for(ring=0;ring<9;ring++){
        float weights[4],center[3];long double jitter=(long double)(portable_crt_rand_step(m)*7u)*real(m,0x575294);
        for(point=0;point<4;point++)weights[point]=real(m,0x6255c0+ring*16+point*4);
        for(axis=0;axis<3;axis++){
            center[axis]=(float)((((long double)controls[1][axis]*weights[1]+(long double)controls[0][axis]*weights[0])+(long double)controls[3][axis]*weights[3])+(long double)controls[2][axis]*weights[2]);
            store(m,0x625650+axis*4,center[axis]);
        }
        for(point=0;point<3;point++)for(axis=0;axis<3;axis++){
            unsigned vector=point==0?2:point==1?1:0;long double displacement=(long double)offsets[vector][axis]*jitter;
            if(axis)displacement=(float)displacement;
            store(m,positions+(ring*3+point)*12+axis*4,(float)(displacement+center[axis]));
        }
    }
    for(band=0;band<8;band++)for(face=0;face<6;face++){
        unsigned triangle=band*6+face,i;GameAddress packet=model+0x58+triangle*40,uv=render_uv+triangle*24;
        game_memory_write_u32(m,packet,3);game_memory_write_u32(m,packet+4,game_memory_read_u32(m,model+0x4c)+triangle*12);
        game_memory_write_u32(m,packet+16,uv);
        for(i=0;i<24;i+=4)game_memory_write_u32(m,uv+i,game_memory_read_u32(m,source_uv+face*24+i));
    }
    far_bits=game_memory_read_u32(m,0x597f7c);memcpy(&far,&far_bits,4);
    submission.matrix=0x5cedf0;submission.source_vertices=positions;submission.transformed_vertices=game_memory_read_u32(m,model+0x44);
    submission.polygons=model+0x58;submission.vertex_count=27;submission.polygon_count=48;submission.flags=0x1d;
    submission.far_depth=(float)((long double)far-real(m,0x575298));
    return !m->fault && gameplay_geometry_submit_mesh(m,&submission);
}
